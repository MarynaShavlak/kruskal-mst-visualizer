// Перекладач, що інжектиться у білдери trace. Тримаємо тип у lib (а не імпортуємо
// з i18n), щоб lib/ лишався фреймворк-незалежним: білдер кличе t(key, vars) із
// рядковим ключем, а застосунок передає обгортку над useT. За відсутності
// перекладача (тести) повертаємо ключ як є — нарацію в тестах не перевіряють.

export type Translate = (
  key: string,
  vars?: Record<string, string | number>,
) => string

/** Дефолтний перекладач: повертає ключ без підстановок (для тестів/без i18n). */
export const identityTranslate: Translate = (key) => key

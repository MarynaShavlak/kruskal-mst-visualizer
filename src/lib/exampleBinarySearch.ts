// Канонічні приклади двійкового пошуку (еталон коректності з README та
// Python-репозиторію algo-binary-search). Кожен інстанс — пара (ВІДСОРТОВАНИЙ
// масив, шукане значення): передумова двійкового пошуку. Ті самі пари розбирає
// навчальна вкладка; їхні відомі підсумки (індекс / кількість кроків) звіряють
// тести. «Ціна» — кількість КРОКІВ (порівнянь arr[mid] з x), а це O(log n). Без React.

import type { SearchCase } from "@/lib/exampleLinearSearch"

/** Основний масив із конспекту (11 елементів, відсортований). */
const MAIN: readonly number[] = [1, 3, 5, 8, 10, 12, 15, 18, 20, 22, 24]

/**
 * Основний інстанс: масив `[1,3,5,8,10,12,15,18,20,22,24]`, шукаємо `15` →
 * індекс `6` за **3 кроки**. На ньому README веде весь покроковий розбір
 * (повне трасування з 8 кадрів = step_00…step_07).
 */
export const BS_INTRO: SearchCase = { values: MAIN, target: 15 }

/** Приклад-драйвер із конспекту: `[2,3,4,10,40]`, шукаємо `10` → індекс 3. */
export const BS_CONSPECT: SearchCase = { values: [2, 3, 4, 10, 40], target: 10 }

/** Той самий масив, шукаємо `18` → індекс 7 за **4 кроки** (підказка конспекту). */
export const BS_FOUR_STEPS: SearchCase = { values: MAIN, target: 18 }

/** Найкращий випадок: `12` — це перший обчислений `mid` → **1 крок**, O(1). */
export const BS_BEST: SearchCase = { values: MAIN, target: 12 }

/** Гірший: `11` відсутній → повний спуск log n до -1 (порожній діапазон, 4 кроки). */
export const BS_ABSENT: SearchCase = { values: MAIN, target: 11 }

/**
 * Дублікати `[1,2,2,2,3,4]`, шукаємо `2`: базовий пошук дає ЯКИЙСЬ індекс збігу
 * (2), а межі `lowerBound`=1 / `upperBound`=4 — перше/за останнім входженням
 * (кількість входжень = 3).
 */
export const BS_DUPLICATES: SearchCase = { values: [1, 2, 2, 2, 3, 4], target: 2 }

/** Відомі підсумки головного прикладу (з README): індекс 6 за 3 кроки. */
export const BS_INTRO_STATS = {
  result: 6,
  steps: 3,
} as const

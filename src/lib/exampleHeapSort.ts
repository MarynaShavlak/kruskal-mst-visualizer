// Канонічні приклади пірамідального сортування. Головний масив узято з конспекту
// GoIT (heap_sort([12, 11, 13, 5, 6, 7])). Ті самі масиви розбирає навчальна вкладка;
// їхні відомі підсумки (порівняння/обміни) звіряють тести. Без React.

/**
 * Головний навчальний масив `[12, 11, 13, 5, 6, 7]` (6 елементів, з конспекту).
 * Max-купа (asc): 14 порівнянь / 10 обмінів → `[5, 6, 7, 11, 12, 13]`.
 * Min-купа (desc): 16 порівнянь / 13 обмінів → `[13, 12, 11, 7, 6, 5]`.
 */
export const HEAP_INTRO: readonly number[] = [12, 11, 13, 5, 6, 7]
/** Відсортований за зростанням (max-купа). */
export const HEAP_INTRO_SORTED_ASC: readonly number[] = [5, 6, 7, 11, 12, 13]
/** Відсортований за спаданням (min-купа). */
export const HEAP_INTRO_SORTED_DESC: readonly number[] = [13, 12, 11, 7, 6, 5]

/** Відомі підсумки головного прикладу. */
export const HEAP_INTRO_STATS = {
  asc: { comparisons: 14, swaps: 10 },
  desc: { comparisons: 16, swaps: 13 },
} as const

/**
 * Уже відсортований `[1..6]` — демонструє НЕадаптивність: купу все одно треба
 * перебудувати (зростаючий масив — це min-купа, а нам потрібна max-купа), тож
 * роботи навіть БІЛЬШЕ, ніж на зворотному. Max-купа: 16 порівнянь / 14 обмінів.
 */
export const HEAP_SORTED: readonly number[] = [1, 2, 3, 4, 5, 6]

/**
 * Зворотно відсортований `[6..1]` — це вже майже max-купа, тож роботи МЕНШЕ за
 * «вже відсортований»: 14 порівнянь / 9 обмінів. Контрінтуїтивний доказ того, що
 * ціна Heap Sort не залежить від «впорядкованості» так, як в адаптивних методів.
 */
export const HEAP_REVERSED: readonly number[] = [6, 5, 4, 3, 2, 1]

/**
 * Масив із дублікатами `[4, 2, 4, 1, 2, 4]` → `[1, 2, 2, 4, 4, 4]` (12 / 7).
 * Демонструє НЕстабільність: рівні ключі можуть помінятися відносним порядком.
 */
export const HEAP_DUPLICATES: readonly number[] = [4, 2, 4, 1, 2, 4]


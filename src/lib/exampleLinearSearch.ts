// Канонічні приклади лінійного пошуку (еталон коректності з README та
// Python-репозиторію algo-linear-search). Ті самі пари «масив + ціль» розбирає
// навчальна вкладка; їхні відомі підсумки (індекс / кількість перевірок) звіряють
// тести. На відміну від сортувань, тут немає обмінів — «ціна» це КІЛЬКІСТЬ
// ПЕРЕВІРОК (порівнянь arr[i] == x). Без React.

/** Пара «масив, у якому шукаємо + значення target». */
export interface SearchCase {
  readonly values: readonly number[]
  readonly target: number
}

/**
 * Основний приклад із конспекту `([5, 3, 8, 1, 4], шукаємо 8)`: збіг усередині
 * скану — індекс 2, 3 перевірки. На ньому README веде весь покроковий розбір
 * (зокрема повне трасування з 8 кадрів).
 */
export const LS_MAIN: SearchCase = { values: [5, 3, 8, 1, 4], target: 8 }

/** Найкращий випадок: елемент спереду `([5,3,8,1,4], 5)` → індекс 0, 1 перевірка (O(1)). */
export const LS_BEST: SearchCase = { values: [5, 3, 8, 1, 4], target: 5 }

/** Гірший-знайдено: елемент у кінці `([5,3,8,1,4], 4)` → індекс 4, 5 перевірок. */
export const LS_WORST: SearchCase = { values: [5, 3, 8, 1, 4], target: 4 }

/** Відсутній: повний скан до -1 `([5,3,8,1,4], 7)` → -1, 5 перевірок (теж гірший). */
export const LS_ABSENT: SearchCase = { values: [5, 3, 8, 1, 4], target: 7 }

/**
 * Дублікати `([4, 8, 3, 8, 1, 8], шукаємо 8)`: базовий пошук повертає ПЕРШИЙ збіг
 * (індекс 1, 2 перевірки), `find_all` — усі входження `[1, 3, 5]` (повний скан,
 * 6 перевірок). Показує різницю «перший збіг» vs «усі входження».
 */
export const LS_DUPLICATES: SearchCase = { values: [4, 8, 3, 8, 1, 8], target: 8 }

/**
 * Відсортований приклад із конспекту `([1, 3, 5, 7, 9, 11], шукаємо 7)` → індекс 3,
 * 4 перевірки. Місток до двійкового пошуку (на ВПОРЯДКОВАНих даних O(log n)).
 */
export const LS_SORTED: SearchCase = { values: [1, 3, 5, 7, 9, 11], target: 7 }

/** Відомі підсумки головного прикладу (з README): знайдено на індексі 2 за 3 перевірки. */
export const LS_MAIN_STATS = {
  result: 2,
  comparisons: 3,
} as const

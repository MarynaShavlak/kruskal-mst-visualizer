// Спільні чисті утиліти над масивами чисел (без залежностей від UI).

/**
 * Чи впорядкований масив за неспаданням (ascending)? Спільна реалізація для сортувань
 * (перевірка результату) і для пошуків, де відсортованість — ПЕРЕДУМОВА коректності:
 * на невпорядкованих даних двійковий / інтерполяційний / індексно-послідовний пошук
 * може «відкинути» половину чи блок, де насправді лежить шукане.
 */
export function isSorted(seq: readonly number[]): boolean {
  for (let i = 0; i < seq.length - 1; i++) {
    if (seq[i] > seq[i + 1]) return false
  }
  return true
}
